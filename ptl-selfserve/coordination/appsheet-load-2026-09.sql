-- PTL AppSheet backup load: window 2026-09-01 .. 2026-10-06 (built 2026-10-07)
-- Files: ~/Downloads/PTL_APP_SHEET_BACKFILLED_DATA_2026-09.csv (19,489 rows)
--        ~/Downloads/PTL_BATCH_LEVEL_APP_SHEET_OLD_2026-09.csv  (6,531 rows)
-- The Snowflake MCP rejects DML/DDL, so run this yourself. Re-runnable: MERGE is idempotent.
-- Last ~7 days of the window (30 Sep - 6 Oct) are still sparse by design; the October run fills them.

-- 0. Pre-merge backups. IF NOT EXISTS so a re-run can never overwrite the pre-merge state.
CREATE TABLE IF NOT EXISTS PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA_BKP_20261007
  CLONE PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA;
CREATE TABLE IF NOT EXISTS PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD_BKP_20261007
  CLONE PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD;

-- 1. Stage tables (same shape as targets). Load the *_2026-09.csv files into them with
--    Snowsight "Load data into table" (CSV, skip 1 header row), or the *_noheader.csv with PUT/COPY.
CREATE OR REPLACE TABLE PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_ORDERS_2026_09
  LIKE PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA;
CREATE OR REPLACE TABLE PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_BATCHES_2026_09
  LIKE PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD;

-- 2. Gate: stop here unless these match 19,489 and 6,531 and the max timestamps are not in the future.
SELECT (SELECT COUNT(*) FROM PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_ORDERS_2026_09)  AS stg_orders,   -- 19489
       (SELECT COUNT(*) FROM PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_BATCHES_2026_09) AS stg_batches,  -- 6531
       (SELECT MAX(PICKED_UP_AT) FROM PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_ORDERS_2026_09) AS max_pickup; -- 2026-10-03 16:14:00

-- 3. Validation: overlapping keys where BOTH sides are non-null and disagree. Expect 0 on every column.
--    (Overlap is the 1-4 Sep files the August run already loaded; ~2.2k orders.)
SELECT COUNT(*) AS overlap_orders,
       COUNT_IF(s.BATCH_ID          IS NOT NULL AND t.BATCH_ID          IS NOT NULL AND s.BATCH_ID          <> t.BATCH_ID)          AS d_batch,
       COUNT_IF(s.WEIGHT            IS NOT NULL AND t.WEIGHT            IS NOT NULL AND s.WEIGHT            <> t.WEIGHT)            AS d_weight,
       COUNT_IF(s.REACHED_PICKUP_AT IS NOT NULL AND t.REACHED_PICKUP_AT IS NOT NULL AND s.REACHED_PICKUP_AT <> t.REACHED_PICKUP_AT) AS d_reached_pickup,
       COUNT_IF(s.PICKED_UP_AT      IS NOT NULL AND t.PICKED_UP_AT      IS NOT NULL AND s.PICKED_UP_AT      <> t.PICKED_UP_AT)      AS d_picked_up,
       COUNT_IF(s.REACHED_DROP_AT   IS NOT NULL AND t.REACHED_DROP_AT   IS NOT NULL AND s.REACHED_DROP_AT   <> t.REACHED_DROP_AT)   AS d_reached_drop,
       COUNT_IF(s.DELIVERED_AT      IS NOT NULL AND t.DELIVERED_AT      IS NOT NULL AND s.DELIVERED_AT      <> t.DELIVERED_AT)      AS d_delivered,
       COUNT_IF(s.ACCEPTED_AT       IS NOT NULL AND t.ACCEPTED_AT       IS NOT NULL AND s.ACCEPTED_AT       <> t.ACCEPTED_AT)       AS d_accepted,
       COUNT_IF(s.ASSIGNED_AT       IS NOT NULL AND t.ASSIGNED_AT       IS NOT NULL AND s.ASSIGNED_AT       <> t.ASSIGNED_AT)       AS d_assigned
FROM PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_ORDERS_2026_09 s
JOIN PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA t USING (ORDER_ID);

-- 4. MERGE orders. COALESCE(source, target): a blank in a later run never erases a value.
MERGE INTO PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA t
USING PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_ORDERS_2026_09 s ON t.ORDER_ID = s.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  BATCH_ID          = COALESCE(s.BATCH_ID,          t.BATCH_ID),
  WEIGHT            = COALESCE(s.WEIGHT,            t.WEIGHT),
  REACHED_PICKUP_AT = COALESCE(s.REACHED_PICKUP_AT, t.REACHED_PICKUP_AT),
  PICKED_UP_AT      = COALESCE(s.PICKED_UP_AT,      t.PICKED_UP_AT),
  REACHED_DROP_AT   = COALESCE(s.REACHED_DROP_AT,   t.REACHED_DROP_AT),
  DELIVERED_AT      = COALESCE(s.DELIVERED_AT,      t.DELIVERED_AT),
  ACCEPTED_AT       = COALESCE(s.ACCEPTED_AT,       t.ACCEPTED_AT),
  ASSIGNED_AT       = COALESCE(s.ASSIGNED_AT,       t.ASSIGNED_AT)
WHEN NOT MATCHED THEN INSERT
  (ORDER_ID, BATCH_ID, WEIGHT, REACHED_PICKUP_AT, PICKED_UP_AT, REACHED_DROP_AT, DELIVERED_AT, ACCEPTED_AT, ASSIGNED_AT)
  VALUES (s.ORDER_ID, s.BATCH_ID, s.WEIGHT, s.REACHED_PICKUP_AT, s.PICKED_UP_AT, s.REACHED_DROP_AT, s.DELIVERED_AT, s.ACCEPTED_AT, s.ASSIGNED_AT);

-- 5. MERGE batches.
MERGE INTO PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD t
USING PROD_CURATED.PARTLOAD_ANALYTICS.STG_APPSHEET_BATCHES_2026_09 s ON t.BATCH_ID = s.BATCH_ID
WHEN MATCHED THEN UPDATE SET
  BATCH_STATUS        = COALESCE(s.BATCH_STATUS,        t.BATCH_STATUS),
  ROUTE_NAME          = COALESCE(s.ROUTE_NAME,          t.ROUTE_NAME),
  BATCH_CREATED_AT    = COALESCE(s.BATCH_CREATED_AT,    t.BATCH_CREATED_AT),
  ACCEPTED_BY_EMAIL   = COALESCE(s.ACCEPTED_BY_EMAIL,   t.ACCEPTED_BY_EMAIL),
  ACCEPTED_AT         = COALESCE(s.ACCEPTED_AT,         t.ACCEPTED_AT),
  ASSIGNED_VEHICLE_ID = COALESCE(s.ASSIGNED_VEHICLE_ID, t.ASSIGNED_VEHICLE_ID),
  ASSIGNED_AT         = COALESCE(s.ASSIGNED_AT,         t.ASSIGNED_AT)
WHEN NOT MATCHED THEN INSERT
  (BATCH_ID, BATCH_STATUS, ROUTE_NAME, BATCH_CREATED_AT, ACCEPTED_BY_EMAIL, ACCEPTED_AT, ASSIGNED_VEHICLE_ID, ASSIGNED_AT)
  VALUES (s.BATCH_ID, s.BATCH_STATUS, s.ROUTE_NAME, s.BATCH_CREATED_AT, s.ACCEPTED_BY_EMAIL, s.ACCEPTED_AT, s.ASSIGNED_VEHICLE_ID, s.ASSIGNED_AT);

-- 6. Backfill ACCEPTED_AT/ASSIGNED_AT for orders whose batch came from an earlier month's file
--    (296 orders in this build reference batches not in the Sep files). Fills NULLs only.
UPDATE PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA o
SET ACCEPTED_AT = COALESCE(o.ACCEPTED_AT, b.ACCEPTED_AT),
    ASSIGNED_AT = COALESCE(o.ASSIGNED_AT, b.ASSIGNED_AT)
FROM PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD b
WHERE o.BATCH_ID = b.BATCH_ID AND o.ORDER_ID >= 108007
  AND (o.ACCEPTED_AT IS NULL OR o.ASSIGNED_AT IS NULL)
  AND (b.ACCEPTED_AT IS NOT NULL OR b.ASSIGNED_AT IS NOT NULL);

-- 7. Post-load checks. Before: orders 112,218 (max id 119,094), batches 42,458.
--    Expect orders max id 135,696; no future PICKED_UP_AT beyond 2026-10-03 from this window.
SELECT COUNT(*) AS n, MAX(ORDER_ID) AS max_id FROM PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA;
SELECT COUNT(*) AS n, MAX(BATCH_ID) AS max_id FROM PROD_CURATED.PARTLOAD_ANALYTICS.PTL_BATCH_LEVEL_APP_SHEET_OLD;
SELECT DATE_TRUNC('day', PICKED_UP_AT) AS d, COUNT(*) FROM PROD_CURATED.PARTLOAD_ANALYTICS.PTL_APP_SHEET_BACKFILLED_DATA
WHERE PICKED_UP_AT >= '2026-08-20' GROUP BY 1 ORDER BY 1;  -- late-Aug days should now be filled in

