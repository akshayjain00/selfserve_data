WITH online AS (
  SELECT CAST(DATE_TRUNC('month', CONVERT_TIMEZONE('UTC','Asia/Kolkata', TO_TIMESTAMP(orders.created_at))) AS DATE) AS dated,
         BATCHED_ORDERS_V1.ORDER_EXTERNAL_ID, batch_id
  FROM PROD_CURATED.PARTLOAD_APPLICATION.BATCHED_ORDERS_V1
  LEFT JOIN PROD_CURATED.PARTLOAD_APPLICATION.ORDERS ON BATCHED_ORDERS_V1.ORDER_EXTERNAL_ID = ORDERS.external_id
  LEFT JOIN PROD_CURATED.PARTLOAD_ANALYTICS.PTL_INTERNAL_USERS ON PTL_INTERNAL_USERS.mobile = ORDERS.customer_mobile
  WHERE status = 3
    AND orders.created_at >= DATE '2026-01-01' - INTERVAL '330 MINS'
    AND orders.created_at <= DATE '2026-08-31' - INTERVAL '330 MINS' + INTERVAL '1 day'
    AND CASE WHEN ptl_internal_users.mobile IS NULL THEN 'False' ELSE 'True' END = 'False'
)
SELECT dated, COUNT(DISTINCT ORDER_EXTERNAL_ID) AS clubbed_orders, COUNT(DISTINCT batch_id) AS trips,
       ROUND(COUNT(DISTINCT ORDER_EXTERNAL_ID)/NULLIF(COUNT(DISTINCT batch_id),0),3) AS avg_orders_per_trip
FROM online GROUP BY 1 ORDER BY 1